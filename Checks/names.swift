import Foundation

// Prints the config vocabulary as a Nix list, so the module can validate key
// names at evaluation time instead of letting a typo through to runtime.
// Regenerate with `just gen-nix-keys`; `just test` fails if it drifts.

let names = KeyNames.byName.keys.sorted()
let modifiers = ModifierNames.byName.keys.sorted().map { $0.prefix(1).uppercased() + $0.dropFirst() }

print("# Generated by `just gen-nix-keys`. Do not edit.")
print("{")
print("  keys = [")
for name in names { print("    \"\(name)\"") }
print("  ];")
print("  modifiers = [")
for name in modifiers { print("    \"\(name)\"") }
print("  ];")
print("}")
